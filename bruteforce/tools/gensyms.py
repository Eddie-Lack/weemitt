#!/usr/bin/env python3
"""Writes the engine's symbol table: the N64 address of every game global in weemitt's memory layout.

    python3 tools/gensyms.py weemitt/gen/ram.S > build/linux/symbols.c

gen/ram.S places each global at its N64 offset inside port_ram with labels, .skip and .p2align. This script follows
the same offsets. Labels past the end of the heap (port_hw: the N64's hardware registers) are left out.
"""
import re
import sys

HEAP_END = 0x1800000


def main():
    offset = None
    syms = {}
    for line in open(sys.argv[1]):
        line = line.strip()
        m = re.match(r'SYM\((\w+)\):$', line)
        if m:
            if m.group(1) == 'port_ram':
                offset = 0
            elif offset is not None and offset < HEAP_END:
                syms.setdefault(m.group(1), offset)
            continue
        if offset is None:
            continue
        m = re.match(r'\.skip\s+(\d+)$', line)
        if m:
            offset += int(m.group(1))
            continue
        m = re.match(r'\.p2align\s+(\d+)$', line)
        if m:
            align = 1 << int(m.group(1))
            offset = (offset + align - 1) // align * align
    if not syms:
        sys.exit('gensyms: no symbols found in ' + sys.argv[1])
    out = ['/* Generated by tools/gensyms.py from weemitt/gen/ram.S. Sorted by name. */',
           '#include "engine.h"', '', 'const EngineSymbol engine_symbols[] = {']
    for name in sorted(syms):
        out.append('    {"%s", 0x%08Xu},' % (name, 0x80000000 + syms[name]))
    out += ['};', 'const unsigned engine_symbol_count = %d;' % len(syms), '']
    sys.stdout.write('\n'.join(out))


main()
